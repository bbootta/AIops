# 초기 언어. 사용자가 고르기 전 기본값이며, 선택은 localStorage 에 남는다.
DEFAULT_LANG = "en"

# localStorage 키. 화면 밝기(rynta-theme)와 같은 접두사를 쓴다.
STORAGE_KEY = "rynta-lang"

LANGS = ("en", "ko")

MESSAGES: dict[str, dict[str, str]] = {}


def _m(**kw: str) -> None:
    """`키='한국어||English'` 를 카탈로그에 넣는다.

    항목이 많아 `{"ko": ..., "en": ...}` 를 매번 적으면 카탈로그가 읽히지
    않는다. 구분자는 화면 문자열에 등장하지 않는 `||` 를 쓴다.
    """
    for key, val in kw.items():
        ko, sep, en = val.partition("||")
        if not sep or not en.strip():
            raise ValueError(f"i18n 항목 {key} 에 영문이 없다")
        if key in MESSAGES:
            raise ValueError(f"i18n 키 중복: {key}")
        MESSAGES[key] = {"ko": ko, "en": en}


def _t(section: str, *pairs: str) -> None:
    """`'한국어||English'` 를 순서대로 등록한다. 키는 `섹션-일련번호` 다.

    화면 문자열이 천 건을 넘어가면 항목마다 뜻이 담긴 키를 짓는 비용이
    카탈로그를 읽는 이득보다 커진다. 조회는 한국어 원문으로 하므로 키는
    중복만 피하면 되고, 사람이 볼 때는 두 열짜리 대조표로 읽히는 편이 낫다.
    섹션명을 붙여 두면 어느 화면 묶음인지는 키에서 바로 보인다.
    """
    for i, val in enumerate(pairs):
        ko, sep, en = val.partition("||")
        if not sep or not en.strip():
            raise ValueError(f"i18n 항목 {section}-{i} 에 영문이 없다: {ko!r}")
        key = f"{section}_{i:03d}"
        if key in MESSAGES:
            raise ValueError(f"i18n 키 중복: {key}")
        MESSAGES[key] = {"ko": ko, "en": en}



